# -*- coding: utf-8 -*-
"""Regenerate the topic pages and the main screen's catalog.  Usage: python3 tools/build_site.py (or npm run build)

For every written topic in topics/__init__.py (BUILT), for example b-01 from the package topics/b01:
  topics/b-01.html      the topic page in English and Spanish (from its content.py and diagrams.py), plus Ukrainian
                        when the package has a uk.py (see i18n.py)
  js/topics/b-01.js     its questions and section recaps (from its bank.py)
and once:
  js/catalog.js         categories and topics for the main screen (from catalog.py)

index.html, css/styles.css and the other files in js/ are edited directly and are not generated."""
import html
import json
from pathlib import Path

import i18n
import topics
from build_pdf import render_block, last_section, UI
from catalog import CATEGORIES, N_TOPICS, topic_id

ROOT = Path(__file__).resolve().parent.parent
TOPIC = {"en": "Topic", "es": "Tema", "uk": "Тема"}
ALL_TOPICS = {"en": "‹ All topics · {}", "es": "‹ Todos los temas · {}", "uk": "‹ Усі теми · {}"}
GENERATED = "<!-- Generated by tools/build_site.py. Edit the files in tools/ and rebuild, or your changes will be overwritten. -->"


def write(rel, text):
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def build_catalog():
    cats = []
    for c in CATEGORIES:
        items = []
        for n in range(1, N_TOPICS + 1):
            tid = topic_id(c["id"], n)
            built = tid in topics.BUILT
            items.append(dict(id=tid, n=n, title=c["titles"].get(n), page=f"topics/{tid}.html" if built else None,
                              questions=len(topics.load(tid).BANK) if built else 0,
                              langs=list(i18n.langs(topics.load(tid))) if built else []))
        cats.append(dict(id=c["id"], tag=c["tag"], name=c["name"], sub=c["sub"], topics=items))
    write("js/catalog.js", "// Generated by tools/build_site.py from tools/catalog.py. Do not edit by hand.\n"
          "window.DGT_CATALOG = " + json.dumps({"categories": cats}, ensure_ascii=False, indent=1) + ";\n")


def render_lang(mod, lang):
    """mod: the topic as seen in this language (i18n.view)."""
    ui, meta = UI[lang], mod.META[lang]
    toc, body = [], []
    blks = mod.blocks()
    g, s = str(last_section(blks) + 1), str(last_section(blks) + 2)   # glossary and sources follow the last section
    body.append(f'<div class="band"><div class="eyebrow">{meta["eyebrow"]}</div><h1>{meta["title"]}</h1><p>{meta["lead"]}</p></div>')
    for b in blks:
        if b[0] == "h2":
            num, title = b[1], b[2][lang]
            body.append(f'<h2 id="{lang}-s{num}"><span class="n">{num}</span><span>{title}</span></h2>')
            toc.append((f"s{num}", num, title))
        elif b[0] == "pagebreak":
            continue
        elif b[0] == "table":
            body.append('<div class="tw">' + render_block(b, lang) + "</div>")
        else:
            body.append(render_block(b, lang))
    # glossary + sources
    rows = "".join(f"<tr><td><i>{es}</i></td><td>{en}</td></tr>" for es, en in mod.GLOSSARY)
    body.append(f'<h2 id="{lang}-s{g}"><span class="n">{g}</span><span>{ui["glossary"]}</span></h2>'
                f'<div class="tw"><table class="small"><thead><tr><th>{ui["gl_es"]}</th><th>{ui["gl_en"]}</th></tr></thead><tbody>{rows}</tbody></table></div>')
    toc.append((f"s{g}", g, ui["glossary"]))
    lis = "".join(f'<li><a href="{html.escape(u)}" target="_blank" rel="noopener">{html.escape(t)}</a></li>' for t, u in mod.SOURCES)
    body.append(f'<h2 id="{lang}-s{s}"><span class="n">{s}</span><span>{ui["sources"]}</span></h2><p class="note">{ui["sources_note"]}</p><ul class="src">{lis}</ul>')
    toc.append((f"s{s}", s, ui["sources"]))
    toc_html = "".join(f'<li><a href="#{lang}-{sid}" data-go="{sid}"><b>{n}</b><span>{t}</span></a></li>' for sid, n, t in toc)
    toc_html += f'<li><a class="totest" href="#tests" data-go="tests">{ui["tests"]}</a></li>'
    return toc_html, "".join(body)


def build_topic(tid):
    mod = topics.load(tid)
    cat_id, n = tid.split("-")[0], int(tid.split("-")[1])
    cat = next(c for c in CATEGORIES if c["id"] == cat_id)
    langs = i18n.langs(mod)
    views = {lg: i18n.view(mod, lg) for lg in langs}
    full = views[langs[-1]]          # its bank and recaps carry every language
    BANK, TAGS = full.BANK, full.TAGS
    ids = [q["id"] for q in BANK]
    assert len(ids) == len(set(ids)), f"{tid}: duplicate question ids"
    assert not any(i.startswith("ai") for i in ids), f"{tid}: question ids must not start with 'ai' (reserved for Claude's questions)"
    assert all(q["tag"] in TAGS for q in BANK), f"{tid}: a question uses an unknown tag"
    tags = {k: dict(sec=v["sec"], **{lg: v[lg] for lg in langs}, recap=[list(r) for r in v["recap"]], trap=list(v["trap"])) for k, v in TAGS.items()}
    data = "// Generated by tools/build_site.py from tools/bank.py. Do not edit by hand.\nwindow.DGT_DATA = " + json.dumps({"topic": tid, "category": cat["id"], "langs": list(langs), "title": {lg: views[lg].META[lg]["title"] for lg in langs}, "bank": BANK, "tags": tags}, ensure_ascii=False, indent=1) + ";\n"
    write(f"js/topics/{tid}.js", data)
    back = f"../index.html#{cat['id']}"
    rendered = {lg: render_lang(views[lg], lg) for lg in langs}
    for lg in langs[2:]:
        views[lg].quiz()
        miss = {(m[0].split(" ")[0], repr(m[1])) for m in views[lg].missing}
        if miss:
            print(f"  warning: {tid} has {len(miss)} texts without a {i18n.NAMES[lg]} translation; they show in English. List them with: python3 tools/i18n.py todo {tid}")
    brand = "".join(f'<span class="lang-{lg}">{TOPIC[lg]} {n}</span>' for lg in langs)
    opts = "\n    ".join(f'<option value="{lg}" lang="{lg}">{i18n.NAMES[lg]}</option>' for lg in langs)
    group = "Language / Idioma" + (" / Мова" if "uk" in langs else "")
    rail_back = "".join(f'<span class="lang-{lg}">{ALL_TOPICS[lg].format(cat["name"].get(lg, cat["name"]["en"]))}</span>' for lg in langs)
    tocs = "".join(f'<ol class="lang-{lg}">{rendered[lg][0]}</ol>' for lg in langs)
    articles = "\n    ".join(f'<article class="doc lang-{lg}">{rendered[lg][1]}</article>' for lg in langs)
    doc = f"""<!DOCTYPE html>
<html lang="en" data-lang="en" data-langs="{' '.join(langs)}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Topic {n} · {cat['name']['en']} · DGT Study Desk</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=Archivo:wght@600;800&family=Source+Sans+3:ital,wght@0,400;0,600;0,700;1,400&display=swap" rel="stylesheet">
<link rel="stylesheet" href="../css/styles.css">
</head>
<body>
<header class="bar"><div class="bar-in">
  <a class="brand" href="{back}"><span class="back" aria-hidden="true">‹</span><span class="tag">DGT · {cat['tag']}</span>{brand}</a>
  <span class="sync" id="sync"><i></i><span></span></span>
  <span class="langsel"><select id="lang-select" aria-label="{group}">
    {opts}
  </select></span>
  <div class="seg" role="group" aria-label="Theme / Tema">
    <button type="button" id="theme-light" data-theme-btn="light" aria-pressed="true">Light</button>
    <button type="button" id="theme-dark" data-theme-btn="dark" aria-pressed="false">Dark</button>
  </div>
</div></header>
<div class="shell">
  <nav class="rail" aria-label="Sections"><a class="rail-back" href="{back}">{rail_back}</a>{tocs}</nav>
  <main>
    {articles}
    <section id="tests">
      <h2><span class="n">✓</span><span id="tests-h">Tests</span></h2>
      <div class="desk" id="desk"></div>
    </section>
  </main>
</div>
<script src="../js/shared.js"></script>
<script src="../js/topics/{tid}.js"></script>
<script src="../js/app.js"></script>
</body>
</html>"""
    first, rest = doc.split("\n", 1)
    write(f"topics/{tid}.html", first + "\n" + GENERATED + "\n" + rest)
    print(f"built topics/{tid}.html and js/topics/{tid}.js;", len(BANK), "questions;", ", ".join(i18n.NAMES[lg] for lg in langs))


def main():
    for tid in topics.BUILT:
        build_topic(tid)
    build_catalog()
    print("built js/catalog.js;", sum(N_TOPICS for _ in CATEGORIES), "topics in", len(CATEGORIES), "categories,", len(topics.BUILT), "ready")


if __name__ == "__main__":
    main()
